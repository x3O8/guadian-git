def describe(cwes: list) -> list[tuple[str, str, str]]:
    """[(id, name, impact)] for the CWEs we know; unknown ids are listed by id only."""
    rows = []
    for c in cwes or []:
        name, impact = CWE.get(c, (None, None))
        rows.append((c, name or "see the advisory", impact or "see the advisory for impact"))
    return rows
